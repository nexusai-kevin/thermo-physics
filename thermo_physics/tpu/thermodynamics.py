"""
thermo_physics.tpu.thermodynamics
=================================
Non-Equilibrium Thermodynamic Work, Heat Dissipation, and Jarzynski Equality Verification.
Tracks:
1. Instantaneous external work dW = (dH/dt) dt along non-equilibrium trajectories.
2. Heat dissipation dQ into the thermal environment (Sekimoto stochastic energetics & First Law).
3. Non-conservative Housekeeping Heat dQ_hk generated by dynamic auxiliary vector fields.
4. Total medium entropy production Delta S_med = sum dQ_diss / T.
5. Non-isothermal generalized fluctuation relation:
   Sigma = int beta(t) (dH/dt) dt - int (d beta/dt) H(x, t) dt
6. Sequential Monte Carlo (SMC / Jarzynski-Neal AIS) Population Resampling:
   Systematic resampling whenever Kish N_eff / B drops below 50%, maintaining population diversity.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple

import numpy as np

from thermo_physics.tpu.hamiltonian import NonConvexIsingSAT


@dataclass
class JarzynskiAnalysis:
    """Statistical evaluation of the Jarzynski Equality and Second Law dissipation."""
    num_trajectories: int
    beta: float
    mean_work: float
    std_work: float
    min_work: float
    max_work: float
    jarzynski_exp_avg: float            # <exp(-beta * W)> or <exp(-Sigma)>
    delta_f_jarzynski: float            # - (1 / beta) * ln <exp(-beta * W)>
    mean_dissipated_work: float         # <W> - Delta F >= 0
    second_law_satisfied: bool          # True if <W> >= Delta F
    bootstrap_ci_95: Tuple[float, float]
    jensen_gap: float                   # <W> - Delta F_jarzynski
    n_eff: float = 0.0                  # Effective sample size: (sum w)^2 / sum(w^2)
    collapse_ratio: float = 1.0         # N_eff / num_trajectories
    non_isothermal: bool = False
    delta_beta_f: float = 0.0           # - ln <exp(-Sigma)>
    resample_events_count: int = 0
    mean_q_housekeeping: float = 0.0    # Non-conservative work dissipation


@dataclass
class ThermodynamicTrajectory:
    """Thermodynamic observables logged along an ensemble trajectory."""
    work: np.ndarray                   # Cumulative external mechanical work, shape (B,)
    heat_dissipated: np.ndarray        # Cumulative heat dissipated into bath, shape (B,)
    housekeeping_heat: np.ndarray      # Non-conservative auxiliary vector field dissipation, shape (B,)
    entropy_production: np.ndarray     # Cumulative medium entropy production, shape (B,)
    generalized_sigma: np.ndarray      # Non-isothermal exponent Sigma, shape (B,)
    initial_energy: np.ndarray         # Total initial energy (Kinetic + Potential), shape (B,)
    final_energy: np.ndarray           # Total final energy, shape (B,)
    resample_events_count: int = 0
    n_eff_history: List[float] = field(default_factory=list)
    instantaneous_work_history: List[float] = field(default_factory=list)
    instantaneous_temp_history: List[float] = field(default_factory=list)
    instantaneous_ke_history: List[float] = field(default_factory=list)


class ThermodynamicTracker:
    """Real-time non-equilibrium thermodynamics accumulator with SMC Population Resampling."""

    def __init__(
        self,
        batch_size: int,
        num_variables: int,
        mass: float = 1.0,
        kb: float = 1.0,
        enable_population_resampling: bool = False,
        resample_threshold: float = 0.50,
    ):
        self.b = batch_size
        self.n = num_variables
        self.mass = mass
        self.kb = kb
        self.enable_population_resampling = enable_population_resampling
        self.resample_threshold = resample_threshold

        self.cumulative_work = np.zeros(self.b, dtype=np.float64)
        self.cumulative_heat_diss = np.zeros(self.b, dtype=np.float64)
        self.cumulative_q_hk = np.zeros(self.b, dtype=np.float64)
        self.cumulative_entropy = np.zeros(self.b, dtype=np.float64)
        self.cumulative_sigma = np.zeros(self.b, dtype=np.float64)

        # SMC incremental accumulator & accumulated log-partition
        self.incremental_sigma = np.zeros(self.b, dtype=np.float64)
        self.cumulative_resampled_delta_beta_f: float = 0.0
        self.resample_events_count: int = 0

        self.initial_energy: Optional[np.ndarray] = None
        self.last_total_energy: Optional[np.ndarray] = None
        self.last_temperature: Optional[float] = None

        self.n_eff_history: List[float] = []
        self.history_mean_work: List[float] = []
        self.history_mean_temp: List[float] = []
        self.history_mean_ke: List[float] = []

    def initialize(
        self,
        x: np.ndarray,
        v: np.ndarray,
        hamiltonian: NonConvexIsingSAT,
        alpha_well: float,
        lambda_sat: float,
        initial_temperature: float = 1.0,
        clause_weights: Optional[np.ndarray] = None,
    ) -> None:
        """Record initial potential and kinetic energy before annealing begins."""
        x_mat = np.atleast_2d(x)
        v_mat = np.atleast_2d(v)
        pe = hamiltonian.energy(x_mat, alpha_well=alpha_well, lambda_sat=lambda_sat, clause_weights=clause_weights)
        ke = 0.5 * self.mass * np.sum(v_mat**2, axis=1)
        self.initial_energy = pe + ke
        self.last_total_energy = self.initial_energy.copy()
        self.last_temperature = initial_temperature

    def record_step(
        self,
        x: np.ndarray,
        v: np.ndarray,
        hamiltonian: NonConvexIsingSAT,
        alpha_old: float,
        lambda_old: float,
        alpha_new: float,
        lambda_new: float,
        temperature_old: float,
        temperature_new: float,
        clause_weights_old: Optional[np.ndarray] = None,
        clause_weights_new: Optional[np.ndarray] = None,
        dw_hk: Optional[np.ndarray] = None,
    ) -> None:
        """Record work, heat, entropy production, non-conservative housekeeping work, and non-isothermal functional."""
        x_mat = np.atleast_2d(x)
        v_mat = np.atleast_2d(v)

        # 1. External mechanical work: dW = H(x, lambda_new) - H(x, lambda_old)
        pe_old = hamiltonian.energy(x_mat, alpha_well=alpha_old, lambda_sat=lambda_old, clause_weights=clause_weights_old)
        pe_new = hamiltonian.energy(x_mat, alpha_well=alpha_new, lambda_sat=lambda_new, clause_weights=clause_weights_new)
        delta_w = pe_new - pe_old  # shape (B,)
        self.cumulative_work += delta_w

        # 2. Non-conservative housekeeping heat (rotational auxiliary field dissipation)
        if dw_hk is not None:
            self.cumulative_q_hk += dw_hk

        # 3. Kinetic energy and total internal energy
        ke = 0.5 * self.mass * np.sum(v_mat**2, axis=1)
        current_total_e = pe_new + ke  # shape (B,)

        # 4. First law of thermodynamics: Delta E = W - Q_diss => Q_diss = W - Delta E
        if self.last_total_energy is not None:
            delta_e = current_total_e - self.last_total_energy
            delta_q_diss = delta_w - delta_e
            self.cumulative_heat_diss += delta_q_diss

            # 5. Medium entropy production: Delta S_med = delta_q_diss / T
            safe_temp = max(1e-4, 0.5 * (temperature_old + temperature_new))
            self.cumulative_entropy += (delta_q_diss / safe_temp)

            # 6. Non-Isothermal Generalized Jarzynski Functional
            beta_old = 1.0 / (self.kb * max(1e-4, temperature_old))
            beta_new = 1.0 / (self.kb * max(1e-4, temperature_new))
            delta_beta = beta_new - beta_old
            beta_mid = 0.5 * (beta_old + beta_new)

            delta_sigma = beta_mid * delta_w - delta_beta * pe_new
            self.cumulative_sigma += delta_sigma
            self.incremental_sigma += delta_sigma

        self.last_total_energy = current_total_e.copy()
        self.last_temperature = temperature_new

        # Track history
        self.history_mean_work.append(float(np.mean(self.cumulative_work)))
        self.history_mean_temp.append(float(temperature_new))
        self.history_mean_ke.append(float(np.mean(ke)))

    def check_and_resample(
        self,
        x: np.ndarray,
        v: np.ndarray,
        f_cached: Optional[np.ndarray],
        rng: np.random.Generator,
        y_aux: Optional[np.ndarray] = None,
    ) -> Tuple[np.ndarray, np.ndarray, Optional[np.ndarray], Optional[np.ndarray], bool, float]:
        """SMC Population Resampler: Resamples trajectories when N_eff / B < threshold.

        Returns:
          (x, v, f_cached, y_aux, resampled_flag, current_n_eff)
        """
        # Compute incremental Kish N_eff
        y = -self.incremental_sigma
        y_max = float(np.max(y))
        w = np.exp(y - y_max)
        w_sum = float(np.sum(w))
        w_norm = w / max(1e-12, w_sum)
        n_eff = 1.0 / max(1e-12, float(np.sum(w_norm**2)))
        self.n_eff_history.append(n_eff)

        if not self.enable_population_resampling:
            return x, v, f_cached, y_aux, False, n_eff

        # Check threshold
        if (n_eff / self.b) < self.resample_threshold:
            # 1. Accumulate stage log-partition shift: -ln <exp(-Delta Sigma)>
            stage_lse = y_max + np.log(np.mean(w))
            self.cumulative_resampled_delta_beta_f += -stage_lse
            self.resample_events_count += 1

            # 2. Systematic resampling
            u0 = rng.uniform(0.0, 1.0 / self.b)
            u_grid = u0 + np.arange(self.b) / self.b
            cum_w = np.cumsum(w_norm)
            cum_w[-1] = 1.0
            ancestors = np.searchsorted(cum_w, u_grid)
            ancestors = np.clip(ancestors, 0, self.b - 1)

            x_resampled = x[ancestors].copy()
            v_resampled = v[ancestors].copy()
            f_resampled = f_cached[ancestors].copy() if f_cached is not None else None
            y_resampled = y_aux[ancestors].copy() if y_aux is not None else None

            # Reset incremental functional
            self.incremental_sigma.fill(0.0)

            return x_resampled, v_resampled, f_resampled, y_resampled, True, float(self.b)

        return x, v, f_cached, y_aux, False, n_eff

    def finalize(
        self,
        x: np.ndarray,
        v: np.ndarray,
        hamiltonian: NonConvexIsingSAT,
        alpha_well: float,
        lambda_sat: float,
        clause_weights: Optional[np.ndarray] = None,
    ) -> ThermodynamicTrajectory:
        """Finalize and return complete thermodynamic trajectory summary."""
        x_mat = np.atleast_2d(x)
        v_mat = np.atleast_2d(v)
        pe = hamiltonian.energy(x_mat, alpha_well=alpha_well, lambda_sat=lambda_sat, clause_weights=clause_weights)
        ke = 0.5 * self.mass * np.sum(v_mat**2, axis=1)
        final_energy = pe + ke

        assert self.initial_energy is not None

        # Flush any remaining incremental weights
        if self.enable_population_resampling and np.any(self.incremental_sigma != 0.0):
            y = -self.incremental_sigma
            y_max = float(np.max(y))
            w = np.exp(y - y_max)
            stage_lse = y_max + np.log(np.mean(w))
            self.cumulative_resampled_delta_beta_f += -stage_lse

        return ThermodynamicTrajectory(
            work=self.cumulative_work.copy(),
            heat_dissipated=self.cumulative_heat_diss.copy(),
            housekeeping_heat=self.cumulative_q_hk.copy(),
            entropy_production=self.cumulative_entropy.copy(),
            generalized_sigma=self.cumulative_sigma.copy(),
            initial_energy=self.initial_energy.copy(),
            final_energy=final_energy,
            resample_events_count=self.resample_events_count,
            n_eff_history=list(self.n_eff_history),
            instantaneous_work_history=list(self.history_mean_work),
            instantaneous_temp_history=list(self.history_mean_temp),
            instantaneous_ke_history=list(self.history_mean_ke),
        )


def verify_jarzynski_equality(
    work_samples: np.ndarray,
    beta: float,
    generalized_sigma: Optional[np.ndarray] = None,
    resampled_delta_beta_f: Optional[float] = None,
    resample_events_count: int = 0,
    housekeeping_heat: Optional[np.ndarray] = None,
    n_bootstraps: int = 1000,
    seed: Optional[int] = None,
) -> JarzynskiAnalysis:
    """Verify convergence of the Jarzynski equality with exact Effective Sample Size (N_eff) diagnostics."""
    w = np.asarray(work_samples, dtype=np.float64)
    m = len(w)
    assert m > 0, "Work samples array must be non-empty"

    mean_w = float(np.mean(w))
    std_w = float(np.std(w))
    min_w = float(np.min(w))
    max_w = float(np.max(w))

    is_non_isothermal = (generalized_sigma is not None)
    if is_non_isothermal:
        sigma = np.asarray(generalized_sigma, dtype=np.float64)
        y = -sigma
    else:
        y = -beta * w

    y_max = float(np.max(y))
    exp_shifted = np.exp(y - y_max)
    sum_exp = float(np.sum(exp_shifted))
    weights_norm = exp_shifted / max(1e-12, sum_exp)

    # Kish Effective Sample Size
    sum_sq_weights = float(np.sum(weights_norm**2))
    n_eff = 1.0 / max(1e-12, sum_sq_weights)
    collapse_ratio = float(n_eff / m)

    log_sum_exp = y_max + np.log(np.mean(exp_shifted))
    exp_avg = float(np.exp(min(700.0, log_sum_exp))) if log_sum_exp < 700.0 else float("inf")

    if resampled_delta_beta_f is not None and resample_events_count > 0:
        delta_beta_f = resampled_delta_beta_f
        delta_f = delta_beta_f / beta
    elif is_non_isothermal:
        delta_beta_f = -log_sum_exp
        delta_f = delta_beta_f / beta
    else:
        delta_beta_f = -log_sum_exp
        delta_f = - (1.0 / beta) * log_sum_exp

    dissipated = mean_w - delta_f
    second_law = (mean_w >= delta_f - 1e-6)

    # Bootstrap resampling
    rng = np.random.default_rng(seed)
    boot_delta_f = np.zeros(n_bootstraps, dtype=np.float64)
    for b in range(n_bootstraps):
        sample_indices = rng.choice(m, size=m, replace=True)
        sample_y = y[sample_indices]
        sample_y_max = np.max(sample_y)
        sample_lse = sample_y_max + np.log(np.mean(np.exp(sample_y - sample_y_max)))
        boot_delta_f[b] = - (sample_lse / beta)

    ci_low = float(np.percentile(boot_delta_f, 2.5))
    ci_high = float(np.percentile(boot_delta_f, 97.5))

    mean_q_hk = float(np.mean(housekeeping_heat)) if housekeeping_heat is not None else 0.0

    return JarzynskiAnalysis(
        num_trajectories=m,
        beta=beta,
        mean_work=mean_w,
        std_work=std_w,
        min_work=min_w,
        max_work=max_w,
        jarzynski_exp_avg=exp_avg,
        delta_f_jarzynski=delta_f,
        mean_dissipated_work=dissipated,
        second_law_satisfied=second_law,
        bootstrap_ci_95=(ci_low, ci_high),
        jensen_gap=dissipated,
        n_eff=n_eff,
        collapse_ratio=collapse_ratio,
        non_isothermal=is_non_isothermal,
        delta_beta_f=delta_beta_f,
        resample_events_count=resample_events_count,
        mean_q_housekeeping=mean_q_hk,
    )
